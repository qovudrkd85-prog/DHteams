/* eslint-disable @typescript-eslint/no-require-imports -- Local browser verification. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const { installAccountMock, PASSWORD } = require("./helpers/account-mock.cjs");
const baseURL = process.env.TEST_BASE_URL || "http://localhost:3001";
if (!["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname)) throw new Error("Only local test servers are allowed.");

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const members = [];
    const state = await installAccountMock(context, { members, authenticated: false });
    await context.route("**/rest/v1/**", (route) => route.fulfill({ json: route.request().url().includes("/team_members") ? members : [] }));
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(baseURL);
    await page.getByRole("heading", { name: "다시 만나 반가워요" }).waitFor();
    assert.equal(await page.getByRole("region", { name: "팀원과 출퇴근" }).count(), 0);
    fs.mkdirSync("artifacts", { recursive: true });
    await page.screenshot({ path: "artifacts/account-login-desktop.png", fullPage: true });
    await page.getByRole("button", { name: "회원가입", exact: true }).click();
    await page.getByLabel("아이디", { exact: true }).fill("my_team");
    await page.getByLabel("비밀번호", { exact: true }).fill(PASSWORD);
    await page.getByLabel("비밀번호 확인", { exact: true }).fill("WrongConfirm1!");
    await page.getByRole("button", { name: "회원가입하고 내 설정하기", exact: true }).click();
    assert.equal(members.length, 0);
    await page.getByLabel("비밀번호 확인", { exact: true }).fill(PASSWORD);
    await page.getByRole("button", { name: "회원가입하고 내 설정하기", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "내 설정" });
    await dialog.waitFor();
    await page.keyboard.press("Escape");
    assert.equal(await dialog.isVisible(), true, "First profile must be completed before using the workspace");
    await dialog.getByLabel("이름", { exact: true }).fill("김민수");
    await dialog.getByLabel("직책", { exact: true }).fill("설계팀 · 과장");
    state.failProfile = true;
    await dialog.getByRole("button", { name: "설정하고 시작하기", exact: true }).click();
    await dialog.getByRole("alert").filter({ hasText: "프로필 저장 연결 실패" }).waitFor();
    assert.equal(state.account.member.profile_completed, false);
    assert.equal(await dialog.getByLabel("이름", { exact: true }).inputValue(), "김민수");
    state.failProfile = false;
    await dialog.getByRole("button", { name: "설정하고 시작하기", exact: true }).click();
    await dialog.waitFor({ state: "hidden" });
    assert.equal(state.account.member.profile_completed, true);
    const memberId = state.account.member.id;
    const header = page.locator("header");
    await header.getByText("김민수", { exact: true }).waitFor();
    await header.getByText("설계팀 · 과장", { exact: true }).waitFor();
    await page.reload();
    await header.getByRole("button", { name: "내 설정", exact: true }).click();
    await dialog.getByLabel("이름", { exact: true }).fill("김민수 수정");
    await dialog.getByLabel("직책", { exact: true }).fill("설계팀 · 차장");
    await dialog.getByRole("button", { name: "프로필 저장", exact: true }).click();
    await dialog.waitFor({ state: "hidden" });
    assert.equal(state.account.member.id, memberId);
    await header.getByText("김민수 수정", { exact: true }).waitFor();
    await header.getByRole("button", { name: "내 설정", exact: true }).click();
    await dialog.getByRole("button", { name: "비밀번호 변경", exact: true }).click();
    await dialog.getByLabel("현재 비밀번호", { exact: true }).fill("WrongPassword1!");
    await dialog.getByLabel("새 비밀번호", { exact: true }).fill("ChangedPass123!");
    await dialog.getByLabel("새 비밀번호 확인", { exact: true }).fill("ChangedPass123!");
    await dialog.getByRole("button", { name: "비밀번호 저장", exact: true }).click();
    await dialog.getByRole("alert").filter({ hasText: "현재 비밀번호가 맞지 않습니다." }).waitFor();
    assert.equal(state.account.password, PASSWORD);
    await dialog.getByLabel("현재 비밀번호", { exact: true }).fill(PASSWORD);
    await dialog.getByRole("button", { name: "비밀번호 저장", exact: true }).click();
    await dialog.waitFor({ state: "hidden" });
    await header.getByRole("button", { name: "로그아웃", exact: true }).click();
    await page.getByRole("heading", { name: "다시 만나 반가워요" }).waitFor();
    assert.equal(await page.getByRole("region", { name: "팀원과 출퇴근" }).count(), 0);
    await page.getByLabel("아이디", { exact: true }).fill("my_team");
    await page.getByLabel("비밀번호", { exact: true }).fill(PASSWORD);
    await page.getByRole("button", { name: "우리 사무실 들어가기", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "아이디 또는 비밀번호가 맞지 않습니다." }).waitFor();
    await page.getByLabel("비밀번호", { exact: true }).fill("ChangedPass123!");
    await page.getByRole("button", { name: "우리 사무실 들어가기", exact: true }).click();
    await header.getByText("김민수 수정", { exact: true }).waitFor();
    assert.equal(state.account.member.id, memberId);
    await page.setViewportSize({ width: 390, height: 844 });
    await header.getByRole("button", { name: "내 설정", exact: true }).click();
    await dialog.waitFor();
    await page.mouse.move(380, 830);
    await page.waitForFunction(() => document.querySelectorAll('[data-sonner-toast]').length === 0);
    await page.screenshot({ path: "artifacts/account-settings-mobile.png", animations: "disabled" });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await dialog.getByRole("button", { name: "취소", exact: true }).click();
    state.expire();
    await page.evaluate(() => window.dispatchEvent(new Event("teams:session-expired")));
    await page.getByRole("heading", { name: "다시 만나 반가워요" }).waitFor();
    await page.screenshot({ path: "artifacts/account-login-mobile.png", fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.deepEqual(await page.evaluate(() => Object.keys(localStorage).filter((key) => /auth-token|current-member/.test(key))), []);
    assert.deepEqual(errors, []);
    console.log("PASS: signup, mandatory own settings, failed save retry, profile persistence, password change, logout/relogin, expired session, mobile, no JS auth storage.");
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
